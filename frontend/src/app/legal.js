/** Реквизиты оператора — из переменных сборки (VITE_OPERATOR_*). */
export function operator() {
  const o = config.operator
  return {
    name: o.name || 'Администрация сервиса «Родословная»',
    details: [o.inn && `ИНН ${o.inn}`, o.ogrn && `ОГРН ${o.ogrn}`].filter(Boolean).join(', '),
    address: o.address,
    email: config.supportEmail,
    site: config.siteUrl || 'сайт «Родословная»',
    filled: !!(o.name && o.inn && o.address),
  }
}

